-- Добавляет пробникам "раздел" (section) — подзаголовок внутри вкладки на
-- странице «Пробники»: например "Глава 1", под ним пробники 1.1–1.5, дальше
-- "Глава 2" и т.д. Пробники без раздела показываются без подзаголовка.
-- Не трогает уже существующие данные.
-- Выполнить в Supabase: SQL Editor -> New query -> вставить -> Run.

alter table practice_tests add column if not exists section text;

-- Сразу проставляем раздел тем, у кого в названии есть "Глава N" / "Глава N.M":
-- "Глава 1.2" -> "Глава 1", "Пробник: Глава 3.4 часть 2" -> "Глава 3".
-- Уже заполненные разделы не перезаписываются. Дальше раздел меняется в
-- админке, в редактировании пробника.
update practice_tests
set section = 'Глава ' || substring(title from 'Глава\s*(\d+)')
where section is null and title ~ 'Глава\s*\d+';
